//! A stroke ("vector") font.
//!
//! The arcade original had no bitmap font: text was drawn with the same line
//! generator as the ships and rocks. Using macroquad's built-in raster font for
//! the HUD would look anachronistic next to the wireframe art, so each glyph
//! here is a short list of polylines in a 3-wide by 5-tall cell with the origin
//! at the top-left and +y pointing down.

use macroquad::prelude::*;

use crate::render;

type Strokes = &'static [&'static [(f32, f32)]];

pub const GLYPH_H: f32 = 5.0;
const GLYPH_W: f32 = 3.0;
/// Horizontal gap between glyph cells, in cell units.
const GAP: f32 = 1.7;
const ADVANCE: f32 = GLYPH_W + GAP;

/// Total advance width of a string rendered at the given cap height.
pub fn text_width(s: &str, size: f32) -> f32 {
    let n = s.chars().count();
    if n == 0 {
        return 0.0;
    }
    (n as f32 * ADVANCE - GAP) * (size / GLYPH_H)
}

/// Draws `s` with the top-left of the first glyph cell at (`x`, `y`).
pub fn draw(s: &str, x: f32, y: f32, size: f32, thickness: f32, color: Color) {
    let scale = size / GLYPH_H;
    let mut pen = x;
    let mut buf: Vec<Vec2> = Vec::with_capacity(8);

    for ch in s.chars() {
        for stroke in glyph(ch.to_ascii_uppercase()) {
            buf.clear();
            buf.extend(
                stroke
                    .iter()
                    .map(|&(gx, gy)| vec2(pen + gx * scale, y + gy * scale)),
            );
            render::polyline(&buf, false, thickness, color);
        }
        pen += ADVANCE * scale;
    }
}

/// Draws `s` horizontally centred on `cx`.
pub fn draw_centered(s: &str, cx: f32, y: f32, size: f32, thickness: f32, color: Color) {
    draw(s, cx - text_width(s, size) / 2.0, y, size, thickness, color);
}

/// Closed shapes repeat their first point rather than relying on a `closed`
/// flag, which keeps every stroke a plain open polyline.
#[rustfmt::skip]
fn glyph(c: char) -> Strokes {
    match c {
        '0' => &[&[(0., 0.), (3., 0.), (3., 5.), (0., 5.), (0., 0.)]],
        '1' => &[&[(0.8, 0.9), (1.7, 0.), (1.7, 5.)], &[(0.6, 5.), (2.8, 5.)]],
        '2' => &[&[(0., 0.), (3., 0.), (3., 2.5), (0., 2.5), (0., 5.), (3., 5.)]],
        '3' => &[&[(0., 0.), (3., 0.), (3., 5.), (0., 5.)], &[(0.6, 2.5), (3., 2.5)]],
        '4' => &[&[(0., 0.), (0., 2.5), (3., 2.5)], &[(3., 0.), (3., 5.)]],
        '5' => &[&[(3., 0.), (0., 0.), (0., 2.5), (3., 2.5), (3., 5.), (0., 5.)]],
        '6' => &[&[(3., 0.), (0., 0.), (0., 5.), (3., 5.), (3., 2.5), (0., 2.5)]],
        '7' => &[&[(0., 0.), (3., 0.), (3., 5.)]],
        '8' => &[&[(0., 0.), (3., 0.), (3., 5.), (0., 5.), (0., 0.)], &[(0., 2.5), (3., 2.5)]],
        '9' => &[&[(3., 2.5), (0., 2.5), (0., 0.), (3., 0.), (3., 5.), (0., 5.)]],

        'A' => &[&[(0., 5.), (1.5, 0.), (3., 5.)], &[(0.75, 2.6), (2.25, 2.6)]],
        'B' => &[
            &[(0., 0.), (0., 5.)],
            &[(0., 0.), (2.3, 0.), (3., 0.8), (3., 1.7), (2.3, 2.5), (0., 2.5)],
            &[(2.3, 2.5), (3., 3.3), (3., 4.2), (2.3, 5.), (0., 5.)],
        ],
        'C' => &[&[(3., 0.8), (2.3, 0.), (0.7, 0.), (0., 0.8), (0., 4.2), (0.7, 5.), (2.3, 5.), (3., 4.2)]],
        'D' => &[&[(0., 0.), (2.2, 0.), (3., 1.), (3., 4.), (2.2, 5.), (0., 5.), (0., 0.)]],
        'E' => &[&[(3., 0.), (0., 0.), (0., 5.), (3., 5.)], &[(0., 2.5), (2.2, 2.5)]],
        'F' => &[&[(3., 0.), (0., 0.), (0., 5.)], &[(0., 2.5), (2.2, 2.5)]],
        'G' => &[&[(3., 0.8), (2.3, 0.), (0.7, 0.), (0., 0.8), (0., 4.2), (0.7, 5.), (2.3, 5.), (3., 4.2), (3., 2.7), (1.6, 2.7)]],
        'H' => &[&[(0., 0.), (0., 5.)], &[(3., 0.), (3., 5.)], &[(0., 2.5), (3., 2.5)]],
        'I' => &[&[(0.6, 0.), (2.4, 0.)], &[(1.5, 0.), (1.5, 5.)], &[(0.6, 5.), (2.4, 5.)]],
        'J' => &[&[(2.4, 0.), (2.4, 4.2), (1.7, 5.), (0.7, 5.), (0., 4.2), (0., 3.5)]],
        'K' => &[&[(0., 0.), (0., 5.)], &[(3., 0.), (0., 2.6)], &[(0.9, 1.9), (3., 5.)]],
        'L' => &[&[(0., 0.), (0., 5.), (3., 5.)]],
        'M' => &[&[(0., 5.), (0., 0.), (1.5, 2.), (3., 0.), (3., 5.)]],
        'N' => &[&[(0., 5.), (0., 0.), (3., 5.), (3., 0.)]],
        'O' => &[&[(0.7, 0.), (2.3, 0.), (3., 0.8), (3., 4.2), (2.3, 5.), (0.7, 5.), (0., 4.2), (0., 0.8), (0.7, 0.)]],
        'P' => &[&[(0., 5.), (0., 0.), (2.3, 0.), (3., 0.8), (3., 1.8), (2.3, 2.6), (0., 2.6)]],
        'Q' => &[
            &[(0.7, 0.), (2.3, 0.), (3., 0.8), (3., 4.2), (2.3, 5.), (0.7, 5.), (0., 4.2), (0., 0.8), (0.7, 0.)],
            &[(1.8, 3.6), (3.1, 5.4)],
        ],
        'R' => &[&[(0., 5.), (0., 0.), (2.3, 0.), (3., 0.8), (3., 1.8), (2.3, 2.6), (0., 2.6)], &[(1.5, 2.6), (3., 5.)]],
        'S' => &[&[(3., 0.8), (2.3, 0.), (0.7, 0.), (0., 0.8), (0., 1.8), (0.7, 2.5), (2.3, 2.5), (3., 3.2), (3., 4.2), (2.3, 5.), (0.7, 5.), (0., 4.2)]],
        'T' => &[&[(0., 0.), (3., 0.)], &[(1.5, 0.), (1.5, 5.)]],
        'U' => &[&[(0., 0.), (0., 4.2), (0.7, 5.), (2.3, 5.), (3., 4.2), (3., 0.)]],
        'V' => &[&[(0., 0.), (1.5, 5.), (3., 0.)]],
        'W' => &[&[(0., 0.), (0.4, 5.), (1.5, 2.8), (2.6, 5.), (3., 0.)]],
        'X' => &[&[(0., 0.), (3., 5.)], &[(3., 0.), (0., 5.)]],
        'Y' => &[&[(0., 0.), (1.5, 2.6), (3., 0.)], &[(1.5, 2.6), (1.5, 5.)]],
        'Z' => &[&[(0., 0.), (3., 0.), (0., 5.), (3., 5.)]],

        '.' => &[&[(1.3, 4.6), (1.7, 4.6), (1.7, 5.), (1.3, 5.), (1.3, 4.6)]],
        ',' => &[&[(1.7, 4.3), (1.1, 5.6)]],
        '-' => &[&[(0.4, 2.6), (2.6, 2.6)]],
        '+' => &[&[(0.4, 2.6), (2.6, 2.6)], &[(1.5, 1.5), (1.5, 3.7)]],
        ':' => &[&[(1.5, 1.2), (1.5, 1.7)], &[(1.5, 3.4), (1.5, 3.9)]],
        '!' => &[&[(1.5, 0.), (1.5, 3.4)], &[(1.5, 4.6), (1.5, 5.)]],
        '/' => &[&[(0., 5.), (3., 0.)]],
        '\'' => &[&[(1.5, 0.), (1.5, 1.4)]],
        '(' => &[&[(2.2, 0.), (1., 1.6), (1., 3.4), (2.2, 5.)]],
        ')' => &[&[(0.8, 0.), (2., 1.6), (2., 3.4), (0.8, 5.)]],
        '<' => &[&[(2.4, 0.9), (0.4, 2.5), (2.4, 4.1)]],
        '>' => &[&[(0.6, 0.9), (2.6, 2.5), (0.6, 4.1)]],
        '*' => &[&[(0.3, 1.2), (2.7, 3.8)], &[(2.7, 1.2), (0.3, 3.8)], &[(1.5, 0.9), (1.5, 4.1)]],
        _ => &[], // space and anything unmapped
    }
}
